const data = await mkdtemp(path.join(os.tmpdir(), "blocky-restic-")); process.env.BLOCKY_DATA = data;
const remote = await mkdtemp(path.join(os.tmpdir(), "blocky-offsite-"));
if (process.env.BLOCKY_TEST_RESTIC) process.env.BLOCKY_RESTIC_BINARY = process.env.BLOCKY_TEST_RESTIC;
const root = fileURLToPath(new URL("../", import.meta.url));
const bundled = await build({ stdin: { contents: ['restic', 'backups', 'store', 'control', 'files', 'offsite'].map((name) => `export * from './src/server/${name}';`).join('\n'), resolveDir: root, loader: "ts" }, bundle: true, platform: "node", format: "esm", write: false });
const core = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString("base64")}`);
after(async () => { await rm(data, { recursive: true, force: true }); await rm(remote, { recursive: true, force: true }); });

test("real restic encrypts incremental backups, reuses data, restores JARs and metadata, and keeps full copies usable", { timeout: 180000, skip: process.platform !== "win32" && !process.env.BLOCKY_TEST_RESTIC }, async () => {
  await core.ensureRestic();
  const server = await core.addServer({ ...core.GAME_DEFAULTS, name: "Restic test", software: "paper", version: "1.21.8", memoryMb: 1024, port: 34000, motd: "Test", maxPlayers: 10, difficulty: "normal", icon: "grass" });
  await core.makeDirectory(server.id, "world"); await core.makeDirectory(server.id, "plugins");
  await core.writeText(server.id, "world/level.txt", "original world");
  await core.uploadFile(server.id, "plugins/test.jar", Readable.from(["plugin JAR"]));
  const copy = await core.createBackup(server.id);
  await core.changeControl(server.id, (state) => {
    state.backupPolicy.mode = "incremental";
    state.addons = [{ projectId: "Root0001", versionId: "RootV001", title: "Test plugin", version: "1.0", file: "test.jar", requested: true, optionalDependencies: false, dependencies: [], installedAt: new Date().toISOString() }];
  });
  const large = randomBytes(8 * 1024 ** 2);
  const region = path.join(data, "servers", server.id, "world/region.mca"); await writeFile(region, large);
  const first = await core.createBackup(server.id);
  assert.match(first, /^snapshot-[a-f0-9]{64}$/);
  large[0] ^= 255; await writeFile(region, large);
  await core.writeText(server.id, "world/level.txt", "changed world", undefined, (await core.readText(server.id, "world/level.txt")).revision);
  const second = await core.createBackup(server.id);
  const snapshots = await core.listSnapshots(server.id);
  const original = snapshots.find((snapshot) => `snapshot-${snapshot.id}` === first);
  const changed = snapshots.find((snapshot) => `snapshot-${snapshot.id}` === second);
  assert.ok(changed.summary.data_added_packed < original.summary.data_added_packed, "second backup should reuse existing chunks");
  await core.changeControl(server.id, (state) => { state.addons = []; });
  await core.restoreBackup(server.id, first);
  assert.equal((await core.readText(server.id, "world/level.txt")).content, "original world");
  assert.equal(await readFile(path.join(data, "servers", server.id, "plugins/test.jar"), "utf8"), "plugin JAR");
  assert.equal((await core.getControl(server.id)).addons[0].projectId, "Root0001");
  const listed = await core.listBackups(server.id);
  assert.ok(listed.some((backup) => backup.name === copy && backup.storage !== "incremental"));
  assert.ok(listed.some((backup) => backup.name === first && backup.storage === "incremental"));
  await core.deleteBackup(server.id, second);
  await core.maintainRepository(server.id, false); await core.maintainRepository(server.id, true);
  const password = path.join(data, "backups", server.id, "restic-password");
  await rename(password, `${password}.held`);
  await assert.rejects(core.localRepository(server.id, true), /password is missing/);
  await rename(`${password}.held`, password);
  await core.changeControl(server.id, (state) => { state.backupPolicy.mode = "copy"; });
  await core.restoreBackup(server.id, copy);
  assert.equal((await core.readText(server.id, "world/level.txt")).content, "original world");
});

test("real encrypted off-site copies recover with a passphrase and keep secrets out of public state", { timeout: 180000, skip: process.platform !== "win32" && !process.env.BLOCKY_TEST_RESTIC }, async () => {
  const destination = { kind: "folder", path: remote };
  const passphrase = "correct horse battery staple picnic";
  await assert.rejects(core.configureOffsite({ destination, passphrase: "short", keep: 3, afterBackup: false }), /at least/);
  await core.configureOffsite({ destination, passphrase, keep: 3, afterBackup: false });
  const make = (name, port, software = "paper") => core.addServer({ ...core.GAME_DEFAULTS, name, software, version: "1.21.8", memoryMb: 1024, port, motd: "Test", maxPlayers: 10, difficulty: "normal", icon: "grass" });
  const source = await make("Offsite source", 34001);
  await core.makeDirectory(source.id, "world"); await core.writeText(source.id, "world/level.txt", "remote original");
  await core.changeControl(source.id, (state) => { state.backupPolicy.mode = "incremental"; });
  await core.copyOffsite(source.id, true);
  const publicState = await core.offsiteStatus();
  assert.equal(publicState.configured, true);
  assert.ok(publicState.servers.find((server) => server.id === source.id).lastCopyAt);
  assert.ok(!JSON.stringify(publicState).includes(passphrase));
  assert.ok(!JSON.stringify(publicState).includes("panelPassword"));
  const saved = await readFile(path.join(data, "offsite.json"), "utf8");
  assert.ok(!saved.includes(passphrase)); assert.ok(!saved.includes("panelPassword")); assert.ok(JSON.parse(saved).sealed.startsWith("v1."));
  await assert.rejects(core.discoverOffsite({ destination, passphrase: "incorrect password" }));
  const discovered = await core.discoverOffsite({ destination, passphrase });
  assert.equal(discovered.servers[0].id, source.id);
  assert.ok(!JSON.stringify(discovered).includes("repositoryPassword"));
  const { snapshots } = await core.offsiteSnapshots({ destination, passphrase, serverId: source.id }); assert.ok(snapshots.length);
  const target = await make("Recovery target", 34002);
  await core.makeDirectory(target.id, "world"); await core.writeText(target.id, "world/level.txt", "local previous");
  await core.restoreOffsite(target, { destination, passphrase, serverId: source.id, snapshotId: snapshots[0].id });
  assert.equal((await core.readText(target.id, "world/level.txt")).content, "remote original");
  const safety = (await core.listBackups(target.id)).find((backup) => backup.kind === "safety");
  assert.equal(await readFile(path.join(data, "backups", target.id, safety.name, "world/level.txt"), "utf8"), "local previous");
  const mismatch = await make("Wrong software", 34003, "vanilla");
  await assert.rejects(core.restoreOffsite(mismatch, { destination, passphrase, serverId: source.id, snapshotId: snapshots[0].id }), /same server software/);
  const key = path.join(data, "secret.key"); await rename(key, `${key}.held`);
  await assert.rejects(core.offsiteStatus(), /secret.key is missing/);
  await rename(`${key}.held`, key);
  await core.disconnectOffsite();
  assert.equal((await core.offsiteStatus()).configured, false);
  assert.equal((await core.discoverOffsite({ destination, passphrase })).servers[0].id, source.id);
});

test("off-site destinations reject data-folder aliases and unsafe S3 parameters", async () => {
  await assert.rejects(core.parseDestination({ kind: "folder", path: data }), /outside Blocky/);
  const alias = path.join(remote, "data-junction"); await symlink(data, alias, "junction");
  await assert.rejects(core.parseDestination({ kind: "folder", path: alias }), /outside Blocky/);
  await rm(alias);
  const s3 = { kind: "s3", provider: "other", bucket: "test-bucket", prefix: "blocky", region: "us-east-1", endpoint: "https://s3.example.com", accessKeyId: "key-id", secretAccessKey: "secret-value" };
  assert.equal((await core.parseDestination(s3)).kind, "s3");
  for (const change of [{ prefix: "../escape" }, { endpoint: "http://s3.example.com" }, { endpoint: "https://user:password@s3.example.com" }, { secretAccessKey: "bad\nvalue" }]) await assert.rejects(core.parseDestination({ ...s3, ...change }));
});
